// Show how each of the following numbers will look if displayed by printf with
// %#012.5g as the conversion specification:
// (a) 83.7361
// (b) 29748.6607
// (c) 1054932234.0
// (d) 0.0000235218
//
// My Answer:
// (a) : 0000083.7361 -- wrong. Correct : 00000083.736
// (b) : 0029748.6607 -- wrong. Correct : 00000029749.
// (c) : 1054932234.0 -- wrong. Correct : 001.0549e+09
// (d) : 000000.00002 -- wrong. Correct : 002.3522e-05
//
// 変換指定子 %#012.5g の解釈ルール
// 精度 .5（%gにおける精度指定）
// %f や %e では小数点以下の桁数を意味しますが、%g
// では有効数字の桁数を意味します。つまり「全体で有効数字5桁に丸める」という意味になります。
//
// %g の表示形式の自動切替
// 有効数字5桁に丸めた結果の指数（P）によって、固定小数点形式（%fスタイル）か指数表記形式（%eスタイル）かが自動選択されます。
//
// 指数が -4 以上、かつ 精度(5) 未満なら %f 形式
//
// それ以外（指数が -4 未満、または 5 以上）なら %e 形式
//
// フラグ #
// %g において # フラグを指定すると、末尾の無効な 0
// や小数点を取り除かない（必ず小数点を表示する） という意味になります。
//
// フィールド幅 12 と 0 フラグ
// 全文字数を 12 桁にし、空いた左側のスペースを 0 で埋めます（右寄せ）。
//
// 各問題のステップ解説
// (a) 83.7361
// 有効数字5桁に丸める: 83.7361 → 83.736
//
// 形式判定: 指数は 1（8.37361×10
// 1
//  ）なので -4 以上 5 未満。よって %f 形式（83.736）。
//
// # フラグ: 既に小数点と有効数字があるので変化なし（83.736 の長さは 6 文字）。
//
// 012 幅揃え: 全体で12文字になるよう左側を 0 で埋めます。
//
// 結果: 00000083.736 (文字数: 6つの0 + 83.736の6文字 = 12文字)
//
// (b) 29748.6607
// 有効数字5桁に丸める: 29748.6607 → 29749
//
// 形式判定: 指数は 4（2.97486...×10
// 4
//  ）。
// ※ C言語の仕様上、指数 4 は精度 5 未満なので %f 形式を選択します。
//
// %f 形式で有効数字5桁に丸めると 29749
//
// # フラグ: 整数で終わっていますが、# があるため末尾に小数点が強制付与されます
// → 29749.（長さ 6 文字）。
//
// 012 幅揃え: 左側を 0 で埋めて12文字にします。
//
// 結果: 00000029749.
//
// (c) 1054932234.0
// 有効数字5桁に丸める: 1054932234.0 → 1.0549 x 10^9
//
// 形式判定: 指数は 9（1.0549...×10
// 9
//  ）で、精度 5 以上のため %e 形式（指数表記） に切り替わります。
//
// %e 形式の表記: 1.0549e+09 (または 1.0549e+009)
//
// # フラグ: 変化なし（長さ 10 文字）。
//
// 012 幅揃え: 左側を 0 で埋めて12文字にします。
//
// 結果: 001.0549e+09
//
// (d) 0.0000235218
// 有効数字5桁に丸める: 0.0000235218 → 2.3522 x 10^-5
//
// 形式判定: 指数は −5 （2.35218×10
// −5
//  ）で、−4 未満のため %e 形式（指数表記） に切り替わります。
//
// %e 形式の表記: 2.3522e-05
//
// # フラグ: 変化なし（長さ 10 文字）。
//
// 012 幅揃え: 左側を 0 で埋めて12文字にします。
//
// 結果: 002.3522e-05
//
// 押さえておきたいポイント
// %g を読み解くときは、以下の順番で処理するのがコツです。
//
// まず数値を「有効数字N桁」に丸める
//
// 指数 E（m×10
// E
//  ）を求め、−4≤E<N なら %f 形式、それ以外なら %e 形式にする
//
// # があれば小数点を絶対に残す
//
// 最後に 0 フラグとフィールド幅を適用する
//
// %g
// の精度（.5）が「小数点の後の桁数」ではなく「全体の有効数字」である点が最大の罠ですので、ここを意識して見てみてくださいね。
