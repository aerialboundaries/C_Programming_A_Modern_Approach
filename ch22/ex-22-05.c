// Is there any difference between the printf conversion specifications %. 4d
// and %04d? If so, explain what it is.
//
// My Answer:
// The same  --wrong
//
// 正の数（1以上）を出力するだけなら： %.4d も %04d も同じ結果（例:
// 0042）になります。
//
// 厳密な違い：
//
// %.4d は 「数字の最小桁数（精度）」
//
// %04d は 「フィールド全体の幅＋ゼロ埋めフラグ」
//
// 直撃するケース： 値が 0 で精度 0（%.0d）のとき、%.0d は何も出力しませんが
// %00d は 0 を出力します。
//
// したがって、試験や教科書の回答としては「正の整数では同じ結果になるが、仕様としては異なる（精度指定とフィールド幅＋0埋めフラグの違いがある）」と答えるのが満点になります。
